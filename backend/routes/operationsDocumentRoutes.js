function hireAgingBucketSql(alias = "hi") {
  return `CASE
    WHEN ${alias}.due_date IS NULL OR ${alias}.due_date >= CURDATE() THEN 'Current/not due'
    WHEN DATEDIFF(CURDATE(), ${alias}.due_date) BETWEEN 1 AND 30 THEN '1-30'
    WHEN DATEDIFF(CURDATE(), ${alias}.due_date) BETWEEN 31 AND 60 THEN '31-60'
    WHEN DATEDIFF(CURDATE(), ${alias}.due_date) BETWEEN 61 AND 90 THEN '61-90'
    ELSE 'Over 90'
  END`;
}

function configureWorksheet(sheet, title, columns) {
  sheet.columns = columns.map((column) => ({
    key: column.key,
    width: column.width || 18,
    style: column.style || {},
  }));

  sheet.mergeCells(1, 1, 1, columns.length);
  const titleCell = sheet.getCell(1, 1);
  titleCell.value = title;
  titleCell.font = { bold: true, size: 15 };
  titleCell.alignment = { horizontal: "center", vertical: "middle" };
  titleCell.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "DCE6F1" },
  };
  sheet.getRow(1).height = 28;

  const headerRow = sheet.getRow(3);
  columns.forEach((column, index) => {
    headerRow.getCell(index + 1).value = column.header;
  });
  headerRow.font = { bold: true, color: { argb: "FFFFFF" } };
  headerRow.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: "1E3A5F" },
  };
  headerRow.alignment = { vertical: "middle" };
  headerRow.height = 22;
  sheet.views = [{ state: "frozen", ySplit: 3 }];
  sheet.autoFilter = {
    from: { row: 3, column: 1 },
    to: { row: 3, column: columns.length },
  };
}

function styleDataRows(sheet, moneyKeys = []) {
  for (let rowNumber = 4; rowNumber <= sheet.rowCount; rowNumber += 1) {
    const row = sheet.getRow(rowNumber);
    row.alignment = { vertical: "top", wrapText: true };
    if (rowNumber % 2 === 0) {
      row.fill = {
        type: "pattern",
        pattern: "solid",
        fgColor: { argb: "F7FAFC" },
      };
    }
  }

  moneyKeys.forEach((key) => {
    const column = sheet.getColumn(key);
    column.numFmt = '"GHS" #,##0.00';
  });
}

function addWorkbookSheet(workbook, name, title, columns, rows, moneyKeys = []) {
  const sheet = workbook.addWorksheet(name);
  configureWorksheet(sheet, title, columns);
  rows.forEach((row) => sheet.addRow(row));
  styleDataRows(sheet, moneyKeys);
  return sheet;
}

