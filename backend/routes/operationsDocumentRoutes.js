function positiveId(value) {
  const number = Number(value);
  return Number.isInteger(number) && number > 0 ? number : null;
}

function dateOnly(value) {
  const text = String(value || "").trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(text) ? text : null;
}

function firstDayOfMonth() {
  const date = new Date();
  return new Date(Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), 1))
    .toISOString()
    .slice(0, 10);
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function databaseDate(value) {
  if (!value) return null;
  if (value instanceof Date && !Number.isNaN(value.getTime())) {
    return value.toISOString().slice(0, 10);
  }
  const match = String(value).match(/\d{4}-\d{2}-\d{2}/);
  return match ? match[0] : null;
}

function dateRange(req) {
  const from = dateOnly(req.query.from) || firstDayOfMonth();
  const to = dateOnly(req.query.to) || today();
  return from <= to ? { from, to } : { from: to, to: from };
}

function getBranchId(req) {
  if (activeWorkspaceCode(req) !== "spare_parts") {
    return null;
  }

  const branchId = Number(
    req.user?.branch_id ||
      req.user?.default_branch_id ||
      req.user?.selected_branch?.id ||
      0
  );
  return Number.isInteger(branchId) && branchId > 0 ? branchId : null;
}

function isMissingOperationsTable(error) {
  return error?.code === "ER_NO_SUCH_TABLE" || error?.errno === 1146;
}

function sendSetupError(res, error) {
  if (!isMissingOperationsTable(error)) return false;
  res.status(503).json({
    status: "error",
    code: "OPERATIONS_DOCUMENTS_DATABASE_SETUP_REQUIRED",
    message:
      "Fleet, Mining or Equipment Hire tables are missing. Run the complete local master schema before using Operations Documents & Accounting.",
  });
  return true;
}

